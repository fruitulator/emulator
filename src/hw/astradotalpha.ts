const REV8 = Uint8Array.from({ length: 256 }, (_, v) => {
  let r = 0;
  for (let b = 0; b < 8; b++) if (v & (1 << b)) r |= 0x80 >> b;
  return r;
});

const GLYPHS = 0x90;

export class AstraDotAlpha implements MachineDisplay {
  readonly kind = 'msc' as const;

  readonly chars = new Uint8Array(16);
  duty = 0;
  charsetShift = false;

  private readonly buf = new Uint8Array(96);
  private readonly font = new Uint8Array(GLYPHS * 6);
  private readonly shown = new Uint8Array(16 * 5);
  private cursor = 0;
  windowSize = 16;
  private mode = 0;
  private count = 0;
  private ptr = 0;
  private slot = 0;
  private running = false;
  private clockLine = true;
  private shift = 0;
  private bits = 0;

  constructor() {
    this.reset();
  }

  reset(): void {
    this.clockLine = true;
    this.cursor = 0;
    this.bits = 0;
    this.shift = 0;
    this.running = false;
    this.ptr = 0;
    this.windowSize = 16;
    this.count = 0;
    this.mode = 0;
    this.duty = 0;
    this.buf.fill(0);
    this.chars.fill(0);
    this.font.fill(0);
    for (let i = 0; i < FONT_20_7F.length; i++) this.font[0x20 * 6 + i] = REV8[FONT_20_7F[i]];
  }

  lines(run: boolean, clock: boolean, data: boolean): void {
    if (!run) {
      this.reset();
      this.running = false;
      this.clockLine = clock;
      return;
    }
    this.running = true;
    if (clock !== this.clockLine) {
      if (!clock) {
        this.shift = ((this.shift << 1) | (data ? 1 : 0)) & 0xff;
        if (++this.bits === 8) {
          this.bits = 0;
          this.writeByte(this.shift);
        }
      }
      this.clockLine = clock;
    }
  }

  writeByte(b: number): void {
    b &= 0xff;
    if (!this.running) return;
    if (this.mode) { this.modeByte(b); return; }
    const hi = b & 0xf0;
    if (hi === 0xa0) { this.cursor = b & 0x0f; return; }
    if (hi === 0xc0) { this.windowSize = (b & 0x0f) || 16; return; }
    if (hi === 0xe0 || hi === 0xf0) { this.duty = b & 0x1f; return; }
    if (hi === 0x90 || hi === 0xd0) return;
    if (hi === 0xb0) { this.command(b); return; }
    if (b === 0x2e || b === 0x2c) {
      this.buf[this.cursor * 6 + 5] = this.font[b * 6 + 5];
      return;
    }
    let code = b;
    if (code < 0x20 && this.charsetShift) code += 0x40;
    this.cursor = (this.cursor + 1) & 0x0f;
    this.buf.set(this.font.subarray(code * 6, code * 6 + 6), this.cursor * 6);
    this.chars[15 - this.cursor] = code;
  }

  private command(b: number): void {
    switch (b) {
      case 0xb1: case 0xb2: case 0xb4: this.mode = b; break;
      case 0xb3: this.mode = b; this.count = 0x60; this.ptr = 0; break;
      case 0xb5: this.mode = b; this.buf.copyWithin(0, 1, 0x60); this.ptr = 0x5f; this.clearChars(); break;
      case 0xb6: this.mode = b; this.buf.copyWithin(1, 0, 0x5f); this.ptr = 0; this.clearChars(); break;
      case 0xb7: this.buf.copyWithin(0, 6, 0x60); this.cursor = 14; this.chars.copyWithin(1, 0, 15); this.chars[0] = 0; break;
      case 0xb8: this.buf.copyWithin(6, 0, 0x5a); this.cursor = 15; this.chars.copyWithin(0, 1, 16); this.chars[15] = 0; break;
      default: break;
    }
  }

  private modeByte(b: number): void {
    switch (this.mode) {
      case 0xb1:
        if (this.count === 0) { this.slot = (b & 0x0f) + 0x80; this.count = 6; }
        else {
          this.font[this.slot * 6 + (6 - this.count)] = REV8[b];
          if (--this.count === 0) this.mode = 0;
        }
        return;
      case 0xb2: this.ptr = b; this.mode = 0; return;
      case 0xb3:
        this.column(this.ptr++, b);
        if (--this.count === 0) this.mode = 0;
        return;
      case 0xb4:
        if (this.count === 0) { this.count = b; return; }
        this.column(this.ptr++, b);
        if (--this.count === 0) this.mode = 0;
        return;
      case 0xb5: case 0xb6: this.column(this.ptr, b); this.mode = 0; return;
      default: this.mode = 0;
    }
  }

  private column(i: number, b: number): void {
    if (i < 0 || i >= 96) return;
    this.buf[i] = b;
    this.chars[15 - Math.floor(i / 6)] = 0;
  }

  private clearChars(): void { this.chars.fill(0); }

  cellGlyph(cell: number): Uint8Array {
    const c = 15 - (cell & 15);
    const out = this.shown.subarray((cell & 15) * 5, (cell & 15) * 5 + 5);
    for (let j = 0; j < 5; j++) out[j] = REV8[this.buf[c * 6 + j]];
    return out;
  }

  text(): string {
    return [...this.chars].map((c) => (c >= 0x20 && c < 0x7f ? String.fromCharCode(c) : ' ')).join('');
  }
}
