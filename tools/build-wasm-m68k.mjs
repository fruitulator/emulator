import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const asc = root + 'node_modules/.bin/asc';

export const PERSONALITIES = {
  cpu32: { P_CPU32: true, P_TRACE: false },
  'cpu32-trace': { P_CPU32: true, P_TRACE: true },
};

export function personalitySource(name) {
  const consts = PERSONALITIES[name];
  return '// GENERATED by tools/build-wasm-m68k.mjs before each `asc` pass — do not edit.\n'
    + '// Compile-time personality of wasm/m68k/core.ts; one module per personality.\n'
    + Object.entries(consts).map(([k, v]) => `export const ${k}: bool = ${v};\n`).join('');
}

export function sourceHash(name) {
  const core = readFileSync(root + 'wasm/m68k/core.ts', 'utf8');
  return createHash('sha256').update(core).update(personalitySource(name)).digest('hex').slice(0, 16);
}

const wanted = process.argv.slice(2).length ? process.argv.slice(2) : Object.keys(PERSONALITIES);
for (const name of wanted) {
  if (!PERSONALITIES[name]) throw new Error(`unknown personality '${name}'`);
  writeFileSync(root + 'wasm/m68k/personality.gen.ts', personalitySource(name));
  mkdirSync(root + 'wasm/build', { recursive: true });
  execFileSync(asc, [
    'wasm/m68k/core.ts',
    '--outFile', `wasm/build/m68k.${name}.wasm`,
    '--textFile', `wasm/build/m68k.${name}.wat`,
    '--runtime', 'stub',
    '-O', '--noAssert',
    '--initialMemory', '4',
    '--maximumMemory', '2048',
    '--exportStart', '_start',
  ], { cwd: root, stdio: 'inherit' });
  const wasm = readFileSync(root + `wasm/build/m68k.${name}.wasm`);
  const b64 = wasm.toString('base64');
  writeFileSync(root + `src/cpu/m68kwasm.${name}.data.ts`,
    '// GENERATED by tools/build-wasm-m68k.mjs — do not edit.\n'
    + `// The WebAssembly 68k core (wasm/m68k/core.ts) built for the '${name}' personality,\n`
    + '// base64-encoded so it bundles into the worker without a fetch (CSP-safe).\n'
    + `export const M68K_WASM_SOURCE_HASH = '${sourceHash(name)}';\n`
    + `export const M68K_WASM_B64 = '${b64}';\n`);
  console.log(`built wasm/build/m68k.${name}.wasm (${wasm.length} bytes) + src/cpu/m68kwasm.${name}.data.ts`);
}
