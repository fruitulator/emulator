import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const asc = root + 'node_modules/.bin/asc';
execFileSync(asc, [
  'wasm/coldfire.ts',
  '--outFile', 'wasm/build/coldfire.wasm',
  '--textFile', 'wasm/build/coldfire.wat',
  '--runtime', 'stub',
  '-O', '--noAssert',
  '--initialMemory', '4',
  '--maximumMemory', '1024',
  '--exportStart', '_start',
], { cwd: root, stdio: 'inherit' });

const wasm = readFileSync(root + 'wasm/build/coldfire.wasm');
const b64 = wasm.toString('base64');
writeFileSync(root + 'src/cpu/coldfirewasm.data.ts',
  '// GENERATED by tools/build-wasm-coldfire.mjs — do not edit.\n' +
  '// The WebAssembly ColdFire core (wasm/coldfire.ts), base64-encoded so it\n' +
  '// bundles into the worker without a fetch (CSP-safe).\n' +
  `export const COLDFIRE_WASM_B64 = '${b64}';\n`);
console.log(`built wasm/build/coldfire.wasm (${wasm.length} bytes) + src/cpu/coldfirewasm.data.ts`);
